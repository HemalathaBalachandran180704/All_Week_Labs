# Cell 6 — instantiate Agents + Tasks for executor crew
# map plan agents to actual crewai.Agent objects
agent_map = {}
default_llm = llm_for_agents  # reuse planner LLM (customize per agent if model field present)

for a in plan["agents"]:
    name = a.get("name")
    model_key = a.get("model")
    model_llm = default_llm
    if model_key:
        # create a per-agent LLM if a different model is requested (use same key)
        model_llm = LLM(model=a.get("model"), api_key=(GOOGLE_API_KEY or OPENAI_API_KEY))
    agent_obj = Agent(
        role=a.get("role", name),
        goal=a.get("goal", ""),
        backstory=a.get("backstory", ""),
        llm=model_llm,
        verbose=True
    )
    agent_map[name] = agent_obj

# create Task objects in the order listed (simple sequential runner)
task_objs = []
for t in plan["tasks"]:
    agent_name = t["agent"]
    if agent_name not in agent_map:
        raise ValueError(f"Agent named '{agent_name}' not defined in plan agents.")
    task_objs.append(Task(
        description=t["description"].format(topic="AI regulation"),
        expected_output=t.get("expected_output", ""),
        agent=agent_map[agent_name]
    ))

# Build the executor crew
executor_crew = Crew(
    agents=list(agent_map.values()),
    tasks=task_objs,
    process=Process.sequential,
    verbose=True
)

