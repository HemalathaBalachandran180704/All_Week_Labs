# Cell 2 — helpers
def extract_yaml_from_text(text: str) -> str | None:
    """
    Tries several strategies to extract a YAML block from an LLM output.
    Returns the YAML text or None.
    """
    if not text:
        return None
    # 1) triple-backtick yaml block
    m = re.search(r"```yaml\s*(.+?)\s*```", text, flags=re.S | re.I)
    if m:
        return m.group(1).strip()
    # 2) triple-backtick block without "yaml"
    m = re.search(r"```(.+?)```", text, flags=re.S)
    if m:
        body = m.group(1).strip()
        # Heuristic: starts with 'agents:' or 'tasks:'
        if body.lstrip().startswith(("agents:", "tasks:")):
            return body
    # 3) raw YAML starting at first 'agents:' token
    idx = text.find("agents:")
    if idx != -1:
        cand = text[idx:]
        # attempt parse progressively
        return cand
    return None

def parse_plan_yaml(yaml_text: str) -> dict:
    """Parse YAML and perform basic validation."""
    try:
        plan = yaml.safe_load(yaml_text)
    except Exception as e:
        raise ValueError(f"Invalid YAML: {e}")
    if not isinstance(plan, dict) or "agents" not in plan or "tasks" not in plan:
        raise ValueError("Plan YAML must be a dict with top-level keys 'agents' and 'tasks'.")
    # Basic shape checks
    if not isinstance(plan["agents"], list) or not isinstance(plan["tasks"], list):
        raise ValueError("'agents' and 'tasks' must be lists.")
    return plan

# Cell 3 — create LLM wrapper(s) and Planner agent
# Use the LLM you prefer. Example: Gemini via crewai.LLM (if you provided GOOGLE_API_KEY)
default_model = "gemini/gemini-2.5-flash" if GOOGLE_API_KEY else "openai/gpt-4o-mini"
llm_for_agents = LLM(model=default_model, api_key=GOOGLE_API_KEY or OPENAI_API_KEY)

planner_agent = Agent(
    role="Planner",
    goal=(
        "Given a user request, produce a STRICT YAML plan describing:\n"
        "  - agents: list of agent specs (name, role, goal, optional model)\n"
        "  - tasks: list of tasks (id, agent (name), description, expected_output, optional dependencies)\n\n"
        "Constraints:\n"
        "  - Output only valid YAML (no extra chatty text). If you must include text, wrap YAML in ```yaml blocks.\n"
        "  - Keep tasks small and atomic and refer to agents by 'name'."
    ),
    backstory="Experienced project manager. Output concise valid YAML plan only.",
    llm=llm_for_agents,
    verbose=True
)

planner_task = Task(
    description="Create a YAML plan for: {user_request}\n\nProduce only the YAML.",
    expected_output="A YAML plan containing 'agents' and 'tasks'.",
    agent=planner_agent
)

planner_crew = Crew(
    agents=[planner_agent],
    tasks=[planner_task],
    process=Process.sequential,
    verbose=True
)

# Run planner (example request)
user_request = "Build a 3-step scraper: (1) collect top 5 news articles for a topic; (2) extract headlines + summary; (3) produce one-paragraph digest."
planner_result = planner_crew.kickoff({"user_request": user_request})
print("Planner result (raw):")
pprint(planner_result)

